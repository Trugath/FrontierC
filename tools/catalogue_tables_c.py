"""Generate the typed C catalogue of the catalogue port from the native records
(data/systems/catalogue): seven fallback records, then the keyed
records in search order."""
import configparser
from pathlib import Path

from system_records import ROOT, document

SOURCE = ROOT / 'data/systems/catalogue/catalog.ini'


def records():
    config = configparser.ConfigParser()
    config.read(SOURCE, encoding='ascii')
    return document(config, SOURCE, lambda origin, name: origin.parent / name)['records']


def initializer(row):
    m = row['metadata']
    return ('    {' + f'{row["key"]:#010x}, {m[0]:#x}, {m[1]:#x}, {m[2]:#x}, {m[3]:#x}, {m[4]:#x}, '
            f'{m[5]:#x}, {m[6]:#x}, {m[7]:#x}, {{' + ', '.join(map(hex, row['payload'])) + '}, '
            f'{row["packed"]:#x}, {row["responses"][0]:#x}, {row["responses"][1]:#x}' + '},')


def source():
    rows = records()
    if len(rows) != 7 + 324:
        raise ValueError('catalogue record count changed')
    return ('/* Generated by tools/catalogue_tables_c.py. fe2_catalogue_bind fills these from table/catalogue. */\n'
            'fe2_catalogue_record fe2_catalogue_fallback_records[FE2_SYSTEM_FALLBACKS];\n'
            'fe2_catalogue_record fe2_catalogue_keyed_records[FE2_SYSTEM_KEYED];\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/catalogue/system_tables.h')
    write_tables(parser.parse_args().output)
