"""Generate the pointer region tables (the function-key template and the
missile buttons) for the frontier pointer port from the native resources."""
import csv
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'
TABLES = (('fe2_pointer_function_key_regions', 'main_function_key_regions', 16),
          ('fe2_pointer_missile_regions', 'main_missile_button_regions', 5))


def rows(name):
    with open(RESOURCES / f'{name}.csv', newline='', encoding='ascii') as f:
        return [[int(v) for v in row] for row in csv.reader(f) if row]


def image():
    blob = bytearray()
    for _symbol, name, count in TABLES:
        records = rows(name)
        if len(records) != count or any(len(r) != 5 or any(v < 0 or v > 65535 for v in r) for r in records):
            raise ValueError(name)
        blob += b''.join(struct.pack('<5H', *record) for record in records)
    return bytes(blob)


def source():
    return ('/* Generated by tools/pointer_tables_c.py from the region resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const fe2_pointer_region *fe2_pointer_function_key_regions;\n'
            'const fe2_pointer_region *fe2_pointer_missile_regions;\n'
            'int fe2_pointer_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 210u) return -1;\n'
            '    fe2_pointer_function_key_regions = (const fe2_pointer_region *)(const void *)image;\n'
            '    fe2_pointer_missile_regions = (const fe2_pointer_region *)(const void *)(image + 160u);\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
