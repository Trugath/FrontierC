"""Generate the frontier position port's tables from the native resources:
the variant parameter sets (object_variant_parameter_sets.csv, image 121Ch)
and the two rows the three-bit selector reads past them, which are the
following code's bytes (image 127Ch..129Bh, no relocations)."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'
# 127Ch..129Bh: `or byte [200Bh], 2; call ...; push ax; mov bx, 72h; les si, [7ECh]; ...` as dwords.
PAST_TABLE = [[0x200b0e80, 0xfbeae802, 0x0072bb50, 0x07ec36c4], [0x0800f626, 0x794b0775, 0x02c483f7, 0x065653cb]]


def parameter_sets():
    with open(RESOURCES / 'object_variant_parameter_sets.csv', newline='', encoding='ascii') as f:
        return [[int(v, 0) for v in row if v.strip()] for row in csv.reader(f) if row]


def rows():
    return parameter_sets() + PAST_TABLE


def table():
    import struct
    data = rows()
    if len(data) != 8 or any(len(row) != 4 or any(v < 0 or v > 0xffffffff for v in row) for row in data):
        raise ValueError('variant parameters')
    return b''.join(struct.pack('<4I', *row) for row in data)


def source():
    return ('/* Generated by tools/position_tables_c.py; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint32_t (*fe2_variant_parameters)[4];\n'
            'int fe2_position_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 128u) return -1;\n'
            '    fe2_variant_parameters = (const uint32_t (*)[4])(const void *)image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
