"""Generate typed station tables; image_span/blocks are recovery-only helpers."""
from pathlib import Path
import configparser
import re

from object_record import read_object

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'data/interactions'


def _values(path):
    text = path.read_text(encoding='ascii')
    return [int(tok, 0) for tok in re.split(r'[,\s]+', text.strip()) if tok]


def sections():
    """Recovery-only image sections, including the unused initial selected text."""
    from module_tables import document
    from resource_sources import asset
    from text_references import resolve
    ini = configparser.ConfigParser()
    ini.read(RES / 'tables.ini', encoding='ascii')
    out = []
    for entry in document(ini, RES / 'tables.ini', asset, None)['tables']:
        data = b''.join(value.to_bytes(entry['width'], 'little') for value in entry['values'])
        out.append((entry['label'], entry['start'], entry['end'], data))
    return out


def image_span(start, end):
    """Bytes start..end assembled from the CSV sections (all must cover it)."""
    blob = bytearray(end - start)
    covered = set()
    for _name, s, e, data in sections():
        for i in range(max(s, start), min(e, end)):
            blob[i - start] = data[i - s]
            covered.add(i)
    if covered != set(range(start, end)):
        raise ValueError(f'{start:x}..{end:x} not covered')
    return bytes(blob)


def _array(ctype, name, values, fmt):
    lines = [f'const {ctype} {name}[{len(values)}] = {{']
    for i in range(0, len(values), 12):
        lines.append('    ' + ', '.join(fmt.format(v) for v in values[i:i + 12]) + ',')
    lines.append('};')
    return lines


def native_tables():
    """Read source sections by name, without rebuilding a guest memory image."""
    ini = configparser.ConfigParser()
    ini.read(RES / 'tables.ini', encoding='ascii')
    values = lambda name: _values(RES / ini[name]['file'])
    from station_layout import load
    layout = load()
    from equipment_authoring import records
    items = records(RES / ini['interaction_selection_parameters']['file'])
    return {'colours': values('interaction_colours'),
            'displays': layout['displays'],
            'pagination_text_x': layout['pagination_text_x'],
            'widgets': layout['widgets'],
            'items': items, 'template': list(read_object(RES / 'interaction_object_template.txt')),
            'drives': layout['drives'], 'repairs': layout['repairs']}


def _records(ctype, name, records):
    return [f'const {ctype} {name}[{len(records)}] = {{',
            *('    {' + ', '.join(str(value) for value in record) + '},' for record in records), '};']


def source():
    import station_rules
    native = native_tables()
    lines = ['/* Generated by tools/station_tables_c.py from native station resources; do not edit. */']
    lines += _array('uint8_t', 'fe2_station_colours', native['colours'], '0x{:02x}')
    lines += _records('fe2_station_display', 'fe2_station_displays', native['displays'])
    lines.append(f"const uint16_t fe2_station_pagination_text_x = {native['pagination_text_x']};")
    for name, values in native['widgets'].items():
        lines += _array('uint16_t', 'fe2_station_widgets_' + name, values + [65535], '{}')
    lines += _records('fe2_station_item', 'fe2_station_items', native['items'])
    lines += _array('uint8_t', 'fe2_station_template', native['template'], '0x{:02x}')
    lines += _records('fe2_station_drive', 'fe2_station_drives', native['drives'])
    # Repair charges are signed native words.
    lines += _records('fe2_station_repair', 'fe2_station_repairs',
                      [(text, cost - 65536 if cost >= 32768 else cost) for text, cost in native['repairs']])
    lines.append(station_rules.source())
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


def blocks():
    """(image offset, bytes) of each generated table, for comparison."""
    return [(0xa2, image_span(0xa2, 0xa9)), (0xa9, image_span(0xa9, 0x28b)),
            (0x371, image_span(0x371, 0x58d)), (0x5a9, image_span(0x5a9, 0x6c7)),
            (0x6c7, image_span(0x6c7, 0x78d))]


def csv_match_image(image):
    """Return (name, start) for each CSV section that differs from `image`."""
    return [(name, start) for name, start, end, data in sections()
            if image[start:end] != data]


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'build/c/station/station_tables_data.h')
    write_tables(parser.parse_args().output)
