"""Generate the typed C tables of the navigation navigation port.

From the native navigation resources (data/navigation):
- the two-entry time-point text directory, ending at the zero it shares with
  the drawing table;
- the time-slider widget list (the drawing table from 00EBh);
- the target marker glyph;
- the marker sizes by model size / 16. Index 18 (sizes 288..300) reads the
  byte after the table, the RETF opcode CBh at 010Bh, so the table carries
  that byte as its last entry.
"""
from pathlib import Path

from navigation_resources_c import ROOT, START, resources

DIRECTORY, DIRECTORY_END = 0xa3, 0xea
WIDGETS, WIDGETS_END = 0xeb, 0xf7
MARKER, SIZES, SIZES_END = 0xf7, 0xf9, 0x10c


def source():
    data = resources()
    at = lambda offset: offset - START
    directory = data[at(DIRECTORY):at(DIRECTORY_END)]
    widgets = [int.from_bytes(data[at(o):at(o) + 2], 'little') for o in range(WIDGETS, WIDGETS_END, 2)]
    marker = data[at(MARKER):at(SIZES)]
    sizes = data[at(SIZES):at(SIZES_END)]
    if widgets[-1] != 0xffff or marker[-1] != 0 or len(sizes) != 19:
        raise ValueError('navigation table layout changed')
    if len(data) != 0x6a or len(directory) != 71:
        raise ValueError('navigation table layout changed')
    return ('/* Generated by tools/navigation_tables_c.py from native navigation resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t *fe2_navigation_text_directory;\n'
            'const uint16_t *fe2_navigation_slider_widgets;\n'
            'const uint8_t *fe2_navigation_target_marker;\n'
            'const uint8_t *fe2_navigation_marker_sizes;\n'
            'int fe2_navigation_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 0x6au) return -1;\n'
            '    fe2_navigation_text_directory = image + 1u;\n'
            '    fe2_navigation_slider_widgets = (const uint16_t *)(const void *)(image + 0x49u);\n'
            '    fe2_navigation_target_marker = image + 0x55u;\n'
            '    fe2_navigation_marker_sizes = image + 0x57u;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/navigation/navigation_tables_data.h')
    write_tables(parser.parse_args().output)
