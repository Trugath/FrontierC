"""Native typed chart tables. Layout aliases are resolved at build time."""
from pathlib import Path
import struct
from chart_resources_c import resources
ROOT=Path(__file__).resolve().parents[1]

def source():
    data=bytearray(0x2313)
    for start,blob in resources(): data[start:start+len(blob)]=blob
    word=lambda at: int.from_bytes(data[at:at+2],'little')
    dword=lambda at: int.from_bytes(data[at:at+4],'little')
    lines=['/* Native typed tables generated by tools/chart_tables_c.py. */','#include "galactic_map_tables.h"']
    def array(ctype,name,rows):
        lines.append(f'const {ctype} {name}[{len(rows)}]={{')
        lines.extend('    '+row+',' for row in rows); lines.append('};')
    array('map_catalog_entry','map_catalogs',[
        '{'+','.join(map(str,(word(0xa2+4*i),word(0xa4+4*i),word(0x162+2*i)//2,
            (word(0x164+2*i)-word(0x162+2*i))//2,word(0x1cf2+2*i))))+'}' for i in range(47)])
    array('fe2_map_record','map_catalog_records',['{'+','.join(map(str,(data[0x247+4*i],data[0x246+4*i],data[0x249+4*i],data[0x248+4*i])))+'}' for i in range(117)])
    array('uint16_t','map_catalog_identifiers',[str(word(0x41a+2*i)) for i in range(117)])
    for name,at,n,width in [('map_weights',0x1b92,128,2),('map_count_weights',0x1c90,18,2),
        ('map_identifier_low',0x1cb2,32,1),('map_identifier_high',0x1cd2,32,1),
        ('map_system_palette',0x1d52,384,1),('map_density_palette',0x1ed2,384,1),('map_density_colours',0x217a,128,1)]:
        array('uint16_t' if width==2 else 'uint8_t',name,[str(int.from_bytes(data[at+i*width:at+(i+1)*width],'little')) for i in range(n)])
    array('uint8_t','map_annotation_colours',[str(data[at]) for at in (0x2174,0x2176,0x2178)])
    def string(raw): return '"'+''.join('\\%03o'%b for b in raw)+'"'
    array('char','map_body_separator',[str(b) for b in data[0x2052:0x2056]])
    lines.append('const char map_syllables[32][4]={')
    lines.extend('    '+string(bytes(data[0x1c6+4*i:0x1ca+4*i]).rstrip(b'\0'))+',' for i in range(32)); lines.append('};')
    array('char *const','map_texts',[string(bytes(data[0x504+word(0x504+2*i):]).split(b'\0',1)[0]) for i in range(261)])
    for name,signed in [('map_selected_values',False),('map_query_values',True)]:
        offsets=[i*2 if not signed or i<64 else i*2-256 for i in range(128)]
        array('map_value_window',name,['{'+str(dword(0x1b5a+i))+','+str(dword(0x1b5e+i))+'}' for i in offsets])
    lines.append('const int16_t map_candidate_offsets[2][12]={')
    for at in (0x20c8,0x20e0): lines.append('    {'+','.join(str(struct.unpack_from('<h',data,at+2*i)[0]) for i in range(12))+'},')
    lines.append('};')
    array('map_start','map_starts',['{{'+','.join(str(dword(0x20f8+20*i+4*j)) for j in range(3))+'},'+str(word(0x2104+20*i))+','+str(word(0x2108+20*i))+'}' for i in range(6)])
    # Four-byte descriptor windows and hierarchy kinds have byte indices.
    # Their intentional adjacent-resource aliases become ordinary array entries.
    for name,at in [('map_node_spacing',0x21fb),('map_sprite_x',0x2241),('map_sprite_y',0x2287),('map_sprites',0x22cd)]:
        # Valid kinds extend through 46h (settlements are skipped in hierarchy).
        values=[word(at+i) if at+i+2<=len(data) else 0 for i in range(128)]
        array('uint16_t',name,[str(v) for v in values])
    # Two final annotations alias the following projection table; its zero
    # threshold terminates the scan. Resolve them into the typed array.
    array('map_annotation','map_annotations',['{'+','.join(str(word(0x2056+8*i+2*j)) for j in range(4))+'}' for i in range(14)])
    return '\n'.join(lines)+'\n'

def write_tables(path):
    path.parent.mkdir(parents=True,exist_ok=True); path.write_text(source(),encoding='ascii')
