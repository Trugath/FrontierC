"""Generate the typed C tables of the intro intro port.

From the native intro resources (data/intro and
data/text/intro):
- the model bank (its size word, the 240-slot directory and the models;
  offsets are relative to the directory);
- the text directory (offsets relative to the directory);
- the orbit scene object and the 22 timed scene objects (native object
  records);
- the scene timeline and the orbit interval;
- the initial render vector and classification values.
"""
from pathlib import Path
import struct

from intro_resources_c import ROOT, models, objects, strings, tables, timeline

RENDER_VECTOR, CLASSIFICATION = 0x1c1, 0x1c7
OBJECT_BYTES = 0x11e


def record():
    data = timeline()
    blobs = dict(tables())
    blob = bytearray()
    for scene in data['scenes']:
        blob += struct.pack('<IIHH', scene['start'], scene['end'], scene['divisor'], scene['phase_bias'])
    blob += struct.pack('<II', data['orbit_start'], data['orbit_length'])
    blob += blobs[RENDER_VECTOR] + blobs[CLASSIFICATION]
    if len(blob) != 294:
        raise ValueError('intro table record size changed')
    return bytes(blob)


def source():
    record()
    lines = ['/* Generated by tools/intro_tables_c.py from native intro resources; do not edit. */',
             '#include <stddef.h>',
             'const uint8_t *fe2_intro_model_bank;',
             'const uint8_t *fe2_intro_text_directory;',
             'const uint8_t *fe2_intro_orbit_scene;',
             'const uint8_t *fe2_intro_scenes;',
             'const fe2_intro_window *fe2_intro_scene_windows;',
             'uint32_t fe2_intro_orbit_start;',
             'uint32_t fe2_intro_orbit_length;',
             'const uint16_t *fe2_intro_render_vector;',
             'const uint32_t *fe2_intro_classification;',
             'int fe2_intro_tables_bind(const uint8_t *image, size_t count)',
             '{',
             '    if (!image || count != 294u) return -1;',
             '    fe2_intro_scene_windows = (const fe2_intro_window *)(const void *)image;',
             '    fe2_intro_orbit_start = (uint32_t)image[264] | ((uint32_t)image[265] << 8) |',
             '        ((uint32_t)image[266] << 16) | ((uint32_t)image[267] << 24);',
             '    fe2_intro_orbit_length = (uint32_t)image[268] | ((uint32_t)image[269] << 8) |',
             '        ((uint32_t)image[270] << 16) | ((uint32_t)image[271] << 24);',
             '    fe2_intro_render_vector = (const uint16_t *)(const void *)(image + 272u);',
             '    fe2_intro_classification = (const uint32_t *)(const void *)(image + 278u);',
             '    return 0;',
             '}', '']
    return '\n'.join(lines)


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


def offsets():
    """CS offsets of the data the test adapter maps (test use only)."""
    scenes = objects()
    data = timeline()
    return {'orbit': scenes['initial_scene_object'][0],
            'scenes': [scenes[f'intro_scene_object_{s["scene"]:02d}'][0] for s in data['scenes']],
            'models': models()[0], 'texts': strings()[0]}


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/intro/intro_tables_data.h')
    write_tables(parser.parse_args().output)
