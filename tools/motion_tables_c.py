"""Generate the frontier motion port's tables from the native resources:
the basis turning step costs (basis_rotation_rebuild_costs.csv)."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'


def turn_costs():
    with open(RESOURCES / 'basis_rotation_rebuild_costs.csv', newline='', encoding='ascii') as f:
        return [int(v) for row in csv.reader(f) for v in row if v.strip()]


def table():
    costs = turn_costs()
    if len(costs) != 10 or any(v < 0 or v > 255 for v in costs):
        raise ValueError('turn costs')
    return bytes(costs)


def source():
    return ('/* Generated by tools/motion_tables_c.py; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t *fe2_turn_costs;\n'
            'int fe2_motion_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 10u) return -1;\n'
            '    fe2_turn_costs = image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
