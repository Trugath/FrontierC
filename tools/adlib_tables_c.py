"""Generate the AdLib driver's data image from the native sources.

The pitch-bend curves come from data/adlib/pitch_curves.csv.
The operator offsets and note frequencies come from adlib_sequencer_state.inc.
The music bank comes from data/adlib via adlib_resource_sources.encode.
Stream pointers are image offsets, so those bytes keep the addresses they have
in the recovered driver. Nothing here is taken from the assembled overlay.
"""
import csv
from pathlib import Path

from adlib_resource_sources import ROOT, document, encode

PITCH = ROOT / 'data/adlib/pitch_curves.csv'
IMAGE_END = 0x67dd
PITCH_TABLES = 0x382
OPERATORS = 0x85e
FREQUENCIES = 0x867
BANK = 0x1871


def pitch_image(directory=None):
    """Curves and their pointer table, placed at the recovered image offsets."""
    data = bytearray(IMAGE_END)
    labels = {'pitch_bend_tables': PITCH_TABLES}
    curve_start = PITCH_TABLES + 14 * 2
    count = 0
    pitch = Path(directory) / 'pitch_curves.csv' if directory else PITCH
    with pitch.open(encoding='utf-8-sig', newline='') as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != ['curve', *(f'bend_{i:02d}' for i in range(32))]:
            raise ValueError('Unexpected pitch table columns')
        for row in reader:
            if None in row or any(value is None for value in row.values()):
                raise ValueError('Incomplete or extra pitch table fields')
            if int(row['curve'], 0) != count or count >= 14:
                raise ValueError('Pitch curves must be ordered and contiguous from 0 through 13')
            values = [int(row[f'bend_{i:02d}'], 0) for i in range(32)]
            if any(not 0 <= value <= 255 for value in values):
                raise ValueError('Pitch bend delta must fit one byte')
            at, name = curve_start + count * 32, f'pitch_bend_curve_{count:02d}'
            labels[name] = at
            data[PITCH_TABLES + count * 2:PITCH_TABLES + count * 2 + 2] = at.to_bytes(2, 'little')
            data[at:at + 32] = bytes(values)
            count += 1
    if count != 14:
        raise ValueError('Expected 14 pitch curves')
    return data, labels


def image(directory=None):
    directory = Path(directory) if directory else ROOT / 'data/adlib'
    data, _labels = pitch_image(directory)
    data[OPERATORS:OPERATORS + 9] = bytes((0x00, 0x01, 0x02, 0x08, 0x09, 0x0a, 0x10, 0x11, 0x12))
    frequencies = (0x134, 0x147, 0x15a, 0x16f, 0x184, 0x19c, 0x1b4, 0x1ce, 0x1e9, 0x207, 0x225, 0x246)
    for index, frequency in enumerate(frequencies):
        data[FREQUENCIES + 2 * index] = frequency & 0xff
        data[FREQUENCIES + 2 * index + 1] = (frequency >> 8) & 0xff
    bank = encode(document(directory / 'bank.ini'))
    if BANK + len(bank) != IMAGE_END:
        raise ValueError(f'bank ends at {BANK + len(bank):#x}, expected {IMAGE_END:#x}')
    data[BANK:IMAGE_END] = bank
    return bytes(data)


def ambient_offsets():
    records = document(ROOT / 'data/adlib/bank.ini')['records']
    found = {row['operands']: int(row['offset'], 0) for row in records if row['kind'] == 'label'}
    return found['ambient_pitch_parameter'], found['ambient_level_parameter']


def source():
    data = image()
    pitch, level = ambient_offsets()
    lines = ['/* Generated by tools/adlib_tables_c.py from the native AdLib sources; do not edit. */',
             f'enum {{ FE2_ADLIB_AMBIENT_PITCH = {pitch:#x}, FE2_ADLIB_AMBIENT_LEVEL = {level:#x} }};',
             f'static const uint8_t fe2_adlib_image_template[{len(data)}] = {{']
    for offset in range(0, len(data), 16):
        row = ', '.join(f'0x{byte:02x}' for byte in data[offset:offset + 16])
        lines.append(f'    {row},')
    lines.append('};')
    return '\n'.join(lines) + '\n'


def write_tables(path):
    """Ambient offsets stay compiled. The image itself is a frontier.dat record."""
    import configparser
    config = configparser.ConfigParser(interpolation=None)
    config.optionxform = str
    config.read(ROOT / 'data/adlib/bank.ini', encoding='utf-8')
    pitch = int(config['ambient']['pitch'], 0)
    level = int(config['ambient']['level'], 0)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        '/* Ambient offsets from data/adlib/bank.ini. The image is loaded from frontier.dat. */\n'
        '#include <stddef.h>\n'
        'const uint8_t *fe2_adlib_image_template;\n'
        'size_t fe2_adlib_image_bytes;\n'
        f'enum {{ FE2_ADLIB_AMBIENT_PITCH = {pitch:#x}, FE2_ADLIB_AMBIENT_LEVEL = {level:#x} }};\n',
        encoding='ascii')
