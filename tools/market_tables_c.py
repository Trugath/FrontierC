"""Generate the typed C tables of the market market port.

Every table comes from the native market text and economy resources. Where the
original indexes past the end of a table, or reads word lists embedded in
another table through pointers, the generated array covers exactly the data
the original can reach.
"""
from pathlib import Path

from market_resources_c import ROOT, START, resources

# name, C type, first native byte, element count (including reachable overrun)
VIEWS = (
    ('fe2_market_strength_value_factors', 'uint16_t', 0x0251, 8),
    ('fe2_market_population_value_factors', 'uint16_t', 0x0261, 10),
    ('fe2_market_metadata_value_factors', 'uint16_t', 0x0275, 8),
    ('fe2_market_population_supply_factors', 'uint16_t', 0x0285, 10),
    ('fe2_market_metadata_supply_factors', 'uint16_t', 0x0299, 8),
    ('fe2_market_commodity_parameters', 'uint16_t', 0x02a9, 31 * 4),
    ('fe2_market_record_value_pairs', 'uint16_t', 0x03e1, 16),
    ('fe2_market_record_count_factors', 'uint16_t', 0x0401, 16),
    ('fe2_market_record_reward_factors', 'uint16_t', 0x0421, 17),
    # Attachment vectors: bases 0, 0Eh, 2Ch bytes plus eight per slot.
    ('fe2_market_attachment_vectors', 'uint16_t', 0x0443, 0x124 // 2),
    # Command vectors: bases 0, 1Eh, 3Ch, 5Ah run on into the control vectors.
    ('fe2_market_command_vectors', 'uint16_t', 0x05bb, (0x06eb - 0x05bb) // 2),
    # Control vectors; the 1Eh-based set runs on into the candidate keys.
    ('fe2_market_control_vectors', 'uint16_t', 0x0633, (0x06eb - 0x0633) // 2),
    ('fe2_market_allegiance_candidates', 'uint32_t', 0x066f, 3),
    ('fe2_market_request_9856_rewards', 'uint16_t', 0x067b, 8),
    ('fe2_market_request_9854_rewards', 'uint16_t', 0x068b, 8),
    ('fe2_market_request_9855_rewards', 'uint16_t', 0x069b, 8),
    ('fe2_market_local_record_words', 'uint16_t', 0x06ab, 32),
    ('fe2_market_text_directory', 'uint8_t', 0x00a3, 0x0250 - 0x00a3),
)
CATEGORY_PAIRS = (0x0567, 13)
WIDTH = {'uint8_t': 1, 'uint16_t': 2, 'uint32_t': 4}


def image():
    data = bytearray(0x10000)
    blob = resources()
    data[START:START + len(blob)] = blob
    return bytes(data)


def word(data, at):
    return int.from_bytes(data[at:at + 2], 'little')


def array(lines, ctype, name, values, static=False):
    lines.append(f"{'static ' if static else ''}const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), 12):
        lines.append('    ' + ', '.join(values[i:i + 12]) + ',')
    lines.append('};')


def source():
    lines = [
        '/* Generated by tools/market_tables_c.py. table/market is the market image',
        ' * from 0xa2; fe2_market_bind points these views into that record. */',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '',
    ]
    for name, ctype, _start, _count in VIEWS:
        lines.append(f'const {ctype} *{name};')
    lines.append('fe2_category_values fe2_market_category_values[13];')
    lines.append('')
    lines.append('static const uint8_t *fe2_market_at(const uint8_t *image, unsigned offset)')
    lines.append('{')
    lines.append('    return image + (offset - 0xa2u);')
    lines.append('}')
    lines.append('')
    lines.append('int fe2_market_bind(const uint8_t *image, size_t count)')
    lines.append('{')
    lines.append('    unsigned index;')
    lines.append('    if (!image || count != 0x649u) return -1;')
    for name, ctype, start, _count in VIEWS:
        lines.append(f'    {name} = (const {ctype} *)(const void *)fe2_market_at(image, 0x{start:04x}u);')
    pair, count = CATEGORY_PAIRS
    lines.append(f'    for (index = 0; index < {count}u; ++index) {{')
    lines.append(f'        const uint8_t *pair = fe2_market_at(image, 0x{pair:04x}u) + index * 4u;')
    lines.append('        unsigned entries = (unsigned)pair[0] | ((unsigned)pair[1] << 8);')
    lines.append('        unsigned at = (unsigned)pair[2] | ((unsigned)pair[3] << 8);')
    lines.append('        if (at < 0xa2u || (size_t)(at - 0xa2u) + (size_t)entries * 2u > count) return -1;')
    lines.append('        fe2_market_category_values[index].count = (uint16_t)entries;')
    lines.append('        fe2_market_category_values[index].values =')
    lines.append('            (const uint16_t *)(const void *)fe2_market_at(image, at);')
    lines.append('    }')
    lines.append('    return 0;')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/market/market_tables_data.h')
    write_tables(parser.parse_args().output)
