"""Generate the typed C tables of the offences port from the native resources:
the eleven offences (data/offences), the 301 manual-check
questions (data/ownership) and the text directory
(data/text/offences)."""
from pathlib import Path
import struct

from offence_resources_c import ROOT, resources

TEXT, TEXT_END, CHALLENGES, OFFENCES, END = 0xa3, 0x210, 0x211, 0x6c5, 0x71d


def record():
    data = resources()
    at = lambda offset: offset - 0xa2
    return data[at(CHALLENGES):at(END)]


def source():
    if len(record()) != 301 * 4 + 11 * 8:
        raise ValueError('offence table size changed')
    return ('/* Generated by tools/offences_tables_c.py from native offences resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const fe2_ownership_challenge *fe2_offences_challenges;\n'
            'const fe2_offence *fe2_offences_offences;\n'
            'const uint8_t *fe2_offences_text_directory;\n'
            'int fe2_offences_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 1292u) return -1;\n'
            '    fe2_offences_challenges = (const fe2_ownership_challenge *)(const void *)image;\n'
            '    fe2_offences_offences = (const fe2_offence *)(const void *)(image + 1204u);\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/offences/offence_tables.h')
    write_tables(parser.parse_args().output)
