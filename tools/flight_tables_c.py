"""Generate flight tables from semantic cockpit UI and remaining recovery data.

From the native flight resources (data/cockpit and the
text catalog data/text/flight):
- the player ship template (286 bytes, the allocator's record image);
- the view marker line records;
- the text directory (relative word offsets, then the strings);
- the offscreen target label records (selector, x, y);
- named cockpit icons, slot centres, command keys/hitboxes and drive labels
  from data/cockpit/layout.json;
- the emitted object variants: the per-model block (from the original's
  offset table, as block numbers) and the four blocks of (model,
  parameter) pairs.

`blocks()` reconstructs the recovered image layout for migration checks;
native hitbox termination and typed slot/icon arrays do not share its overlaps.
"""
import configparser
import json
from pathlib import Path
import struct

from module_tables import document
from resource_sources import asset, compile_resource

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / 'data/cockpit/tables.ini'
CATALOG = ROOT / 'data/text/flight/catalog.ini'
VARIANTS = 0x7f4


def source_tables():
    """Read named source sections without assembling an overlay image."""
    config = configparser.ConfigParser()
    config.read(TABLES, encoding='ascii')
    return document(config, TABLES, asset, None)['tables']


def text_block():
    """Encoded text-directory resource; relative offsets are its file format."""
    text = json.loads(Path(compile_resource('strings', CATALOG)).read_text())
    entries = [bytes(e['bytes']) + b'\0' for e in text['entries']]
    relative, offsets = 2 * len(entries), []
    for entry in entries:
        offsets.append(relative)
        relative += len(entry)
    blob = struct.pack(f'<{len(offsets)}H', *offsets) + b''.join(entries)
    if text['directory_offset'] + len(blob) != text['end_offset']:
        raise ValueError('flight text layout changed')
    return text['directory_offset'], blob


def blocks():
    """Recovery-only (image offset, bytes) blocks for migration fixtures."""
    result = [(t['start'], b''.join(v.to_bytes(t['width'], 'little') for v in t['values']))
              for t in source_tables()]
    result.append(text_block())
    return sorted(result)


def array(kind, name, values):
    return f'const {kind} {name}[{len(values)}] = {{' + ', '.join(hex(v) for v in values) + '};'


def source():
    tables = {entry['label']: entry['values'] for entry in source_tables()}
    template = tables['player_ship_template']
    markers = tables['view_marker_coordinates']
    labels = tables['cockpit_text_positions']
    selectors = tables['cockpit_resource_selectors']
    rectangles = tables['view_command_rectangles']
    layout = tables['cockpit_layout_words']
    status = tables['status_panel_words']
    variants = tables['emitted_object_variants']
    # This remaining source is an explicitly legacy pointer table. Decode it
    # here; native gameplay receives block indices, never image addresses.
    offsets = tables['emitted_object_variant_offsets']
    if (len(template) != 0x11e or len(markers) != 16 or len(labels) != 18 or len(selectors) != 15
            or len(rectangles) != 35 or len(layout) != 29 or len(status) != 15
            or len(variants) != 64 or len(offsets) != 16
            or any((o - VARIANTS) % 0x20 or not 0 <= o - VARIANTS < 0x80 for o in offsets)):
        raise ValueError('flight table layout changed')
    lines = ['/* Generated by tools/flight_tables_c.py from native flight resources; do not edit. */']
    lines.append(array('uint8_t', 'fe2_flight_player_template', template))
    lines.append('const int16_t fe2_flight_view_markers[4][4] = {' + ', '.join(
        '{' + ', '.join(str(v - 0x10000 if v & 0x8000 else v) for v in markers[4 * i:4 * i + 4]) + '}'
        for i in range(4)) + '};')
    lines.append('const uint8_t *fe2_flight_text_directory;')
    lines.append('const uint16_t fe2_flight_label_records[6][3] = {' + ', '.join(
        '{' + ', '.join(hex(v) for v in labels[3 * i:3 * i + 3]) + '}' for i in range(6)) + '};')
    lines.append(array('uint8_t', 'fe2_flight_resource_selectors', selectors))
    # The historical sentinel belongs to the next image table. Native C must
    # terminate its own array instead of reading beyond it into another object.
    lines.append(array('uint16_t', 'fe2_flight_command_rectangles', rectangles + [0xffff]))
    lines.append(array('uint8_t', 'fe2_flight_command_keys', rectangles[4::5]))
    from cockpit_layout import load
    cockpit = load()
    for name, records in (('equipment_slot_centres', cockpit['slots']), ('weapon_sprites', cockpit['sprites'])):
        lines.append('const uint16_t fe2_flight_' + name + '[8][2] = {' + ', '.join(
            '{' + ', '.join(map(str, record)) + '}' for record in records) + '};')
    lines.append(array('uint16_t', 'fe2_flight_status_texts', status))
    lines.append(array('uint8_t', 'fe2_flight_variant_blocks', [(o - VARIANTS) // 0x20 for o in offsets]))
    lines.append('const uint16_t fe2_flight_variants[4][8][2] = {' + ', '.join(
        '{' + ', '.join('{' + hex(variants[16 * b + 2 * i]) + ', ' + hex(variants[16 * b + 2 * i + 1]) + '}'
                        for i in range(8)) + '}' for b in range(4)) + '};')
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/flight/flight_tables_data.h')
    write_tables(parser.parse_args().output)
