"""Generate the typed C tables of the commander port from the native resources
(data/text/commander and data/preferences):
the text directory, the default preferences, the preference widgets, the
shape-detail presets, the filename widgets and the file literals."""
from pathlib import Path

from commander_resources_c import ROOT, resources


def record():
    data = resources()[0]
    table = data[0x917 - 0xa2:]
    if len(table) != 0xb4e - 0x917:
        raise ValueError('commander preference record size changed')
    return table


def source():
    record()
    return ('/* Generated by tools/commander_tables_c.py from native commander resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t *fe2_commander_text_directory;\n'
            'const uint8_t *fe2_commander_default_preferences;\n'
            'const uint16_t *fe2_commander_preference_widgets;\n'
            'const uint8_t (*fe2_commander_detail_presets)[4];\n'
            'const uint16_t *fe2_commander_filename_widgets;\n'
            'const char *fe2_commander_commander_directory;\n'
            'const char *fe2_commander_default_name;\n'
            'const char *fe2_commander_default_extension;\n'
            'const char *fe2_commander_parent_label;\n'
            'int fe2_commander_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 567u) return -1;\n'
            '    fe2_commander_default_preferences = image;\n'
            '    fe2_commander_preference_widgets = (const uint16_t *)(const void *)(image + 0x21u);\n'
            '    fe2_commander_detail_presets = (const uint8_t (*)[4])(const void *)(image + 0x159u);\n'
            '    fe2_commander_commander_directory = (const char *)(image + 0x169u);\n'
            '    fe2_commander_filename_widgets = (const uint16_t *)(const void *)(image + 0x1f8u);\n'
            '    fe2_commander_default_name = (const char *)(image + 0x216u);\n'
            '    fe2_commander_default_extension = (const char *)(image + 0x21eu);\n'
            '    fe2_commander_parent_label = (const char *)(image + 0x223u);\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/commander/commander_tables.h')
    write_tables(parser.parse_args().output)
