"""Compile the interaction native text (TSV/INI) into the C port's directory table."""
import configparser
from pathlib import Path
import struct

from string_resources import document
from resource_sources import asset

ROOT=Path(__file__).resolve().parents[1]
SOURCE=ROOT/'data/text/interaction/catalog.ini'


def resources():
    config=configparser.ConfigParser()
    config.read(SOURCE,encoding='ascii')
    data=document(config,SOURCE,asset)
    if (data['module'],data['directory_offset'],data['end_offset'],len(data['entries']))!=(
            'interaction',0xa3,0x4cf9,462): raise ValueError('Interaction catalogue layout changed')
    relative=462*2
    offsets,lengths,blob=[],[],bytearray()
    for entry in data['entries']:
        value=bytes(entry['bytes'])+b'\0'
        offsets.append(0xa3+relative)
        lengths.append(len(value))
        blob.extend(value)
        relative+=len(value)
    if 0xa3+relative!=0x4cf9: raise ValueError('interaction text image length changed')
    directory=struct.pack('<462H',*(offset-0xa3 for offset in offsets))
    return b'\xff'+directory+blob,offsets,lengths


def write_tables(path):
    """The directory is loaded from frontier.dat text/interaction."""
    path.parent.mkdir(parents=True,exist_ok=True)
    path.write_text('/* Generated by tools/interaction_text_c.py; the catalogue is loaded from frontier.dat. */\n'
        'const uint8_t *fe2_interaction_text_text_directory;\n',encoding='ascii')


if __name__=='__main__':
    import argparse
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output',type=Path,default=ROOT/'build/c/interaction/interaction_tables.h')
    write_tables(parser.parse_args().output)
