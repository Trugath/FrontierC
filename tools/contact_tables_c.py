"""Generate the frontier contact port's tables from the native resources:
the nested model axis permutations (contact_axis_permutations.csv, frame
byte offsets; the port keeps the query axis of each component)."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'


def permutations():
    """Rows of four frame byte offsets (the fourth word is unused)."""
    with open(RESOURCES / 'contact_axis_permutations.csv', newline='', encoding='ascii') as f:
        return [[int(v) for v in row] for row in csv.reader(f) if row]


def table_bytes():
    return b''.join(v.to_bytes(2, 'little') for row in permutations() for v in row)


def table():
    rows = permutations()
    if len(rows) != 6 or any(len(row) < 3 or any(v < 0 or v % 2 or v // 2 > 255 for v in row[:3]) for row in rows):
        raise ValueError('contact axes')
    return bytes(v // 2 for row in rows for v in row[:3])


def source():
    return ('/* Generated by tools/contact_tables_c.py; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t (*fe2_contact_axes)[3];\n'
            'int fe2_contact_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 18u) return -1;\n'
            '    fe2_contact_axes = (const uint8_t (*)[3])(const void *)image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
