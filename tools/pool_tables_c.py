"""Generate the drive adjustments of the frontier pool port from the native
resource data/main/frontier/main_object_adjustment_words.csv
(the table at CS:0 of the main image)."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCE = ROOT / 'data/main/frontier/main_object_adjustment_words.csv'


def adjustments():
    with open(RESOURCE, newline='', encoding='ascii') as f:
        return [int(v) for row in csv.reader(f) for v in row if v.strip()]


def table():
    values = adjustments()
    if len(values) != 15 or any(v < 0 or v > 65535 for v in values):
        raise ValueError('drive adjustments')
    return b''.join(v.to_bytes(2, 'little') for v in values)


def source():
    return ('/* Generated by tools/pool_tables_c.py from main_object_adjustment_words.csv; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint16_t *fe2_drive_adjustments;\n'
            'int fe2_pool_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 30u) return -1;\n'
            '    fe2_drive_adjustments = (const uint16_t *)(const void *)image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
