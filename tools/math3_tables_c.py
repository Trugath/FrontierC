"""Generate the C tables of the math port.

Sine, square root and reciprocal come from the formulas in math_samples.
The game keeps the first two in the resident data and the reciprocals in
the math overlay itself."""
from pathlib import Path

from math_samples import reciprocal_lookup, sine_half_cycle, square_root_lookup

ROOT = Path(__file__).resolve().parents[1]


def tables():
    return {'sine': sine_half_cycle(), 'square_root': square_root_lookup(),
            'reciprocal': reciprocal_lookup()}


def source():
    t = tables()
    lines = ['/* Generated by tools/math3_tables_c.py; do not edit. */',
             '#include "math3.h"', '']
    for name, ctype, values in (('sine', 'int16_t', [v - 0x10000 if v & 0x8000 else v for v in t['sine']]),
                                ('square_root', 'uint16_t', t['square_root']),
                                ('reciprocal', 'uint16_t', t['reciprocal'])):
        lines.append(f'const {ctype} fe2_math_{name}[{len(values)}] = {{')
        lines += ['    ' + ', '.join(map(str, values[i:i + 12])) + ',' for i in range(0, len(values), 12)]
        lines.append('};')
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/math/math3_tables.c')
    write_tables(parser.parse_args().output)
