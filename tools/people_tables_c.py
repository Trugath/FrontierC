"""Generate the people port's tables from its native CSV resources.

The Frontier body (image 01B3h) and the creation tables (image 02D1h..
039Fh: the allocation parameters, then the variant values) come from
data/objects. The parameter tables are read by image
offset (drive and marker indexed), so they are kept as one block.
"""
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'data/objects'
TABLES_AT = 0x2d1


def _values(path):
    text = path.read_text(encoding='ascii')
    return [int(tok, 0) for tok in re.split(r'[,\s]+', text.strip()) if tok]


def resources():
    from object_record import read_object
    template = read_object(RES / 'object_template.txt')
    parameters = bytes(_values(RES / 'object_parameter_tables.csv'))
    variants = _values(RES / 'variant_object_values.csv')
    if len(template) != 286 or len(parameters) != 155 or len(variants) != 26:
        raise ValueError('unexpected people table sizes')
    return template, parameters, variants


def tables():
    """Image 02D1h..039Fh."""
    _, parameters, variants = resources()
    return parameters + struct.pack('<26H', *variants)


def source():
    if len(table_blob()) != 286 + 207:
        raise ValueError('people table size changed')
    return '\n'.join([
        '/* Generated by tools/people_tables_c.py from data/objects; do not edit. */',
        '#include <stddef.h>',
        'const uint8_t *fe2_people_template;',
        'const uint8_t *people_tables;',
        'int fe2_people_bind(const uint8_t *image, size_t count)',
        '{',
        '    if (!image || count != 493u) return -1;',
        '    fe2_people_template = image;',
        '    people_tables = image + 286u;',
        '    return 0;',
        '}', ''])


def write_tables(path):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


def table_blob():
    """Image 01B3h..039Fh as the resources give it."""
    return resources()[0] + tables()


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/people/people_tables_data.h')
    write_tables(parser.parse_args().output)
