"""Generate the typed C tables of the status commander status port.

Every table comes from the native status resources (status CSV tables, contract
chances and the text catalog). Where the original indexes past the end of a
table into the data that follows it, the generated array is extended over
exactly the bytes the original can reach, so the C code needs no layout
knowledge.
"""
from pathlib import Path

from status_resources_c import ROOT, blocks
from contract_callback_table import load as load_callbacks
from resource_sources import compile_resource

ACTIONS = {None: 'FE2_CONTRACT_SPAWN_NONE',
           'create_contract_related_object': 'FE2_CONTRACT_SPAWN_ONE',
           'create_two_contract_objects': 'FE2_CONTRACT_SPAWN_TWO',
           'create_three_contract_objects': 'FE2_CONTRACT_SPAWN_THREE',
           'create_contract_mode_four_object': 'FE2_CONTRACT_SPAWN_MODE_FOUR'}

# name, C type, first native byte, element count (including reachable overrun)
VIEWS = (
    ('fe2_status_object_template', 'uint8_t', 0x00a3, 0x11e),
    ('fe2_status_equipment_text', 'uint16_t', 0x01c1, 32),
    ('fe2_status_installed_text', 'uint16_t', 0x01e7, 16),
    ('fe2_status_widget_bytes', 'uint8_t', 0x01fb, 0x30b - 0x1fb),
    ('fe2_status_criminal_thresholds', 'uint32_t', 0x1143, 4),
    ('fe2_status_combat_thresholds', 'uint32_t', 0x1153, 9),
    ('fe2_status_page_sprite_bytes', 'uint8_t', 0x1177, 17),
    ('fe2_status_fuel_capacity', 'uint8_t', 0x1187, 0x1203 - 0x1187),
    ('fe2_status_cargo_subtypes', 'uint8_t', 0x1196, 31),
    ('fe2_status_rank_bounds', 'uint16_t', 0x11b5, 14),
    ('fe2_status_rank_adjustments', 'int8_t', 0x11d1, 7),
    ('fe2_status_contract_text', 'uint16_t', 0x11d7, 8),
    ('fe2_status_mission_text', 'uint16_t', 0x11e7, 7),
    ('fe2_status_mission_authority', 'uint8_t', 0x11f5, 7),
    ('fe2_status_mission_permit', 'int8_t', 0x11fc, 7),
)
WIDTH = {'uint8_t': 1, 'int8_t': 1, 'uint16_t': 2, 'uint32_t': 4}


def image():
    data = bytearray(0x1203)
    for start, blob in blocks():
        data[start:start + len(blob)] = blob
    return bytes(data)


def source():
    data = image()
    lines = ['/* Generated by tools/status_tables_c.py from native status resources; do not edit. */']
    for name, ctype, start, count in VIEWS:
        width = WIDTH[ctype]
        if start + width * count > len(data):
            raise ValueError(f'{name} reaches past the native tables')
        values = []
        for i in range(count):
            value = int.from_bytes(data[start + width * i:start + width * (i + 1)], 'little',
                                   signed=ctype == 'int8_t')
            values.append(str(value) if ctype == 'int8_t' else hex(value))
        lines.append(f'const {ctype} {name}[{count}] = {{')
        for i in range(0, len(values), 12):
            lines.append('    ' + ', '.join(values[i:i + 12]) + ',')
        lines.append('};')
    lines.append('const uint8_t *fe2_status_text_bytes;')
    callbacks = load_callbacks(compile_resource(
        'contract_callbacks', ROOT / 'data/status/contract_callbacks.ini'))
    lines.append('const fe2_contract_chance fe2_status_contract_chances[16] = {')
    for row in callbacks['subtypes']:
        lines.append(f"    {{{row['threshold']:#06x}, {ACTIONS[row['callback']]}}},")
    lines.append('};')
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path,
                        default=ROOT / 'build/c/status/status_tables_data.h')
    write_tables(parser.parse_args().output)
