"""Generate the key translation (DS:8808h: shifted, then unshifted) for the
frontier input port from the native resources."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'


def values(name):
    with open(RESOURCES / f'{name}.csv', newline='', encoding='ascii') as f:
        return [int(v, 0) for row in csv.reader(f) for v in row if v.strip()]


def translation():
    data = values('main_keyboard_shifted') + values('main_keyboard_unshifted')
    if len(data) != 256 or any(v < 0 or v > 255 for v in data):
        raise ValueError('the translation is not 256 bytes')
    return bytes(data)


def source():
    return ('/* Generated by tools/input_tables_c.py from the keyboard resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t *fe2_input_translation;\n'
            'int fe2_input_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 256u) return -1;\n'
            '    fe2_input_translation = image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
