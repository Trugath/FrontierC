"""Generate the typed C tables of the systems system generation port.

Every table comes from the native systems resources: profile tables, the
saturated profile curve, generated-object tables, the handcrafted system
templates with their trailers and keys, and the static Frontier object.
Where the original indexes past the end of a table, the generated array is
extended over exactly the data the original can reach.
"""
from pathlib import Path

from systems_resources_c import ROOT, blocks
from handcrafted_system_keys import load as load_systems
from resource_sources import compile_resource

RECORD = 0x40
SOL = 0x1963
SOL_TEMPLATES = {'daedalus': 2, 'abraham_lincoln': 12, 'apollonius_city': 16, 'galileo': 17}
STATIC_OBJECT = 0x3b1b
# name, C type, first native byte, element count (including reachable overrun)
VIEWS = (
    ('fe2_systems_profile_thresholds', 'uint32_t', 0x00ff, 23),
    ('fe2_systems_profile_or_object_references', 'uint32_t', 0x01b7, 23),
    ('fe2_systems_profile_kind', 'uint16_t', 0x00a3, 23),
    ('fe2_systems_profile_descriptor', 'uint16_t', 0x00d1, 23),
    ('fe2_systems_profile_temperature', 'uint16_t', 0x0189, 23),
    ('fe2_systems_profile_subtree_position', 'uint16_t', 0x015b, 23),
    ('fe2_systems_profile_curve', 'uint16_t', 0x3c39, 256),
    # Index (danger >> 4 & 1Eh) + base + seed bits reaches 37h words.
    ('fe2_systems_generated_descriptors', 'uint16_t', 0x3e39, 0x37),
    ('fe2_systems_station_orbit_parameters', 'uint16_t', 0x3e99, 32),
)
WIDTH = {'uint16_t': 2, 'uint32_t': 4}


def image():
    data = bytearray(0x10000)
    for start, blob in blocks():
        data[start:start + len(blob)] = blob
    return bytes(data)


def array(lines, ctype, name, values, per_line=12):
    lines.append(f'const {ctype} {name}[{len(values)}] = {{')
    for i in range(0, len(values), per_line):
        lines.append('    ' + ', '.join(values[i:i + per_line]) + ',')
    lines.append('};')


def record_literal(data, start):
    return '{{' + ', '.join(hex(b) for b in data[start:start + RECORD]) + '}}'


def template_list(data, start):
    """Records from `start` (the first always counts) up to the zero-lead trailer."""
    records = [start]
    position = start + RECORD
    while int.from_bytes(data[position:position + 4], 'little') != 0:
        records.append(position)
        position += RECORD
    return records, position


def source():
    systems = load_systems(compile_resource(
        'handcrafted_systems', ROOT / 'data/systems/handcrafted/handcrafted_systems.ini'))
    count = len(systems['systems'])
    lines = [
        '/* Generated by tools/systems_tables_c.py. table/systems is the systems image',
        ' * from 0xa2; fe2_systems_bind points these views into that record. */',
        '#include <stddef.h>',
        '#include <stdint.h>',
        '#include <string.h>',
        '',
    ]
    for name, ctype, _start, _count in VIEWS:
        lines.append(f'const {ctype} *{name};')
    for name in SOL_TEMPLATES:
        lines.append(f'fe2_system_record fe2_systems_sol_{name};')
    lines.append(f'fe2_system_template fe2_systems_template_storage[{count + 1}];')
    lines.append(f'fe2_handcrafted_system fe2_systems_handcrafted_systems[{count}];')
    lines.append(f'const unsigned fe2_systems_handcrafted_count = {count};')
    lines.append('const fe2_system_template *fe2_systems_fallback_system;')
    lines.append('static fe2_system_record fe2_systems_unloaded_record;')
    lines.append('static const fe2_system_template fe2_systems_unloaded_body = {&fe2_systems_unloaded_record, 1, 0, 0};')
    lines.append('const fe2_system_template *fe2_systems_unloaded_system = &fe2_systems_unloaded_body;')
    lines.append('const uint8_t *fe2_systems_static_object;')
    lines.append('uint16_t fe2_systems_static_object_model;')
    lines.append('uint8_t fe2_systems_static_object_handle;')
    lines.append('')
    lines.append('static const uint8_t *fe2_systems_at(const uint8_t *image, unsigned offset)')
    lines.append('{')
    lines.append('    return image + (offset - 0xa2u);')
    lines.append('}')
    lines.append('')
    lines.append('static unsigned fe2_systems_u16(const uint8_t *image, unsigned offset)')
    lines.append('{')
    lines.append('    const uint8_t *p = fe2_systems_at(image, offset);')
    lines.append('    return (unsigned)p[0] | ((unsigned)p[1] << 8);')
    lines.append('}')
    lines.append('')
    lines.append('static unsigned fe2_systems_u32(const uint8_t *image, unsigned offset)')
    lines.append('{')
    lines.append('    const uint8_t *p = fe2_systems_at(image, offset);')
    lines.append('    return (unsigned)p[0] | ((unsigned)p[1] << 8) | ((unsigned)p[2] << 16) | ((unsigned)p[3] << 24);')
    lines.append('}')
    lines.append('')
    lines.append('int fe2_systems_bind(const uint8_t *image, size_t count)')
    lines.append('{')
    lines.append(f'    struct {{ unsigned start, records, counters, stations, used; }} found[{count + 1}];')
    lines.append('    unsigned templates = 0, keys = 0, at, index, slot, unused = 0;')
    lines.append('    if (!image || count != 0x3e7fu) return -1;')
    for name, ctype, start, _count in VIEWS:
        lines.append(f'    {name} = (const {ctype} *)(const void *)fe2_systems_at(image, 0x{start:04x}u);')
    for name, index in SOL_TEMPLATES.items():
        offset = SOL + index * RECORD
        lines.append(f'    memcpy(fe2_systems_sol_{name}.bytes, fe2_systems_at(image, 0x{offset:04x}u), 64);')
    lines.append('    fe2_systems_static_object = fe2_systems_at(image, 0x3b1bu);')
    lines.append('    fe2_systems_static_object_model = (uint16_t)fe2_systems_u16(image, 0x3b1bu + 0x5au);')
    lines.append('    fe2_systems_static_object_handle = fe2_systems_at(image, 0x3b1bu)[0x5d];')
    lines.append('    at = 0x1963u;')
    lines.append('    while (at < 0x3b1bu) {')
    lines.append(f'        if (templates == {count + 1}u || at + 64u > 0x3b1bu) return -1;')
    lines.append('        found[templates].start = at;')
    lines.append('        found[templates].records = 0;')
    lines.append('        found[templates].used = 0;')
    lines.append('        do {')
    lines.append('            found[templates].records++;')
    lines.append('            at += 64u;')
    lines.append('            if (at + 10u > 0x3b1bu) return -1;')
    lines.append('        } while (fe2_systems_u32(image, at) != 0u);')
    lines.append('        found[templates].counters = fe2_systems_u32(image, at + 4u);')
    lines.append('        found[templates].stations = fe2_systems_u16(image, at + 8u);')
    lines.append('        at += 10u;')
    lines.append('        ++templates;')
    lines.append('    }')
    lines.append('    if (at != 0x3b1bu) return -1;')
    lines.append('    at = 0x3ed9u;')
    lines.append('    while (at + 6u <= 0x3f1fu) {')
    lines.append('        unsigned key = fe2_systems_u32(image, at);')
    lines.append('        unsigned offset = fe2_systems_u16(image, at + 4u);')
    lines.append('        if (key == 0u) break;')
    lines.append(f'        if (keys == {count}u) return -1;')
    lines.append('        slot = templates;')
    lines.append('        for (index = 0; index < templates; ++index) if (found[index].start == offset) slot = index;')
    lines.append('        if (slot == templates || found[slot].used) return -1;')
    lines.append('        found[slot].used = 1;')
    lines.append('        fe2_systems_template_storage[slot].records =')
    lines.append('            (const fe2_system_record *)(const void *)fe2_systems_at(image, found[slot].start);')
    lines.append('        fe2_systems_template_storage[slot].count = found[slot].records;')
    lines.append('        fe2_systems_template_storage[slot].counters = found[slot].counters;')
    lines.append('        fe2_systems_template_storage[slot].stations = (uint16_t)found[slot].stations;')
    lines.append('        fe2_systems_handcrafted_systems[keys].key = key;')
    lines.append('        fe2_systems_handcrafted_systems[keys].system = &fe2_systems_template_storage[slot];')
    lines.append('        ++keys;')
    lines.append('        at += 6u;')
    lines.append('    }')
    lines.append(f'    if (keys != {count}u) return -1;')
    lines.append('    for (index = 0; index < templates; ++index) if (!found[index].used) {')
    lines.append('        fe2_systems_template_storage[index].records =')
    lines.append('            (const fe2_system_record *)(const void *)fe2_systems_at(image, found[index].start);')
    lines.append('        fe2_systems_template_storage[index].count = found[index].records;')
    lines.append('        fe2_systems_template_storage[index].counters = found[index].counters;')
    lines.append('        fe2_systems_template_storage[index].stations = (uint16_t)found[index].stations;')
    lines.append('        fe2_systems_fallback_system = &fe2_systems_template_storage[index];')
    lines.append('        ++unused;')
    lines.append('    }')
    lines.append('    return unused == 1u ? 0 : -1;')
    lines.append('}')
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/systems/system_tables_data.h')
    write_tables(parser.parse_args().output)
