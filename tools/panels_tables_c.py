"""Generate the typed C tables of the panels port from data/panels.

The palette list is eleven index bytes, the even bytes of each pair. Each
marker pointer is an address of one of those index bytes in the original
image; the colour table is the byte it addresses.
"""
import configparser
from pathlib import Path

from module_tables import document
from resource_sources import asset

ROOT = Path(__file__).resolve().parents[1]
TABLES = ROOT / 'data/panels/tables.ini'
PALETTE = 0xa2


def tables():
    config = configparser.ConfigParser()
    config.read(TABLES, encoding='ascii')
    return {entry['label']: entry for entry in document(config, TABLES, asset, None)['tables']}


def image():
    placed = bytearray(0xfb - 0x9e)
    for entry in tables().values():
        raw = b''.join(value.to_bytes(entry['width'], 'little') for value in entry['values'])
        start = entry['start'] - 0x9e
        placed[start:start + len(raw)] = raw
    return bytes(placed)


def source():
    data = tables()
    palette = data['palette_mapping']
    if palette['start'] != PALETTE or len(palette['values']) != 22:
        raise ValueError('Panel palette layout changed')
    if data['palette_list_end']['values'] != [0xff]:
        raise ValueError('Panel palette list must end with 0xff')
    indices = palette['values'][::2]
    colours = []
    for pointer in data['marker_colour_pointers']['values']:
        offset = pointer - palette['start']
        if offset < 0 or offset >= len(palette['values']) or offset % 2:
            raise ValueError(f'Marker pointer {pointer:#x} is not a palette index')
        colours.append(palette['values'][offset])
    scales = data['drive_gauge_scales']['values']
    mask = data['overlay_event_mask']['values']
    if (len(indices), len(colours), len(scales), len(mask)) != (11, 18, 15, 1):
        raise ValueError('Panel table length changed')
    if len(image()) != 93:
        raise ValueError('Panel image size changed')
    lines = ['/* Generated by tools/panels_tables_c.py from data/panels; do not edit. */',
             '#include <stddef.h>',
             'uint8_t fe2_panels_palette_indices[11];',
             'uint8_t fe2_panels_marker_colours[18];',
             'const uint16_t *fe2_panels_drive_gauge_scales;',
             'uint32_t fe2_panels_event_mask;',
             'int fe2_panels_bind(const uint8_t *image, size_t count)',
             '{',
             '    unsigned i;',
             '    if (!image || count != 93u) return -1;',
             '    fe2_panels_event_mask = (uint32_t)image[0] | ((uint32_t)image[1] << 8) |',
             '        ((uint32_t)image[2] << 16) | ((uint32_t)image[3] << 24);',
             '    for (i = 0; i < 11u; ++i) fe2_panels_palette_indices[i] = image[4u + i * 2u];',
             '    for (i = 0; i < 18u; ++i) {',
             '        unsigned word = (unsigned)image[27u + i * 2u] | ((unsigned)image[28u + i * 2u] << 8);',
             '        unsigned offset = word - 0xa2u;',
             '        if (offset >= 22u || (offset & 1u)) return -1;',
             '        fe2_panels_marker_colours[i] = image[4u + offset];',
             '    }',
             '    fe2_panels_drive_gauge_scales = (const uint16_t *)(const void *)(image + 63u);',
             '    return 0;',
             '}', '']
    return '\n'.join(lines)


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/panels/panel_tables_data.h')
    write_tables(parser.parse_args().output)
