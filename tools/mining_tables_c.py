"""Generate the typed C tables of the mining port from the native resources:
the 27 mining yields and the category-to-commodity map
(data/mining) and the text directory
(data/text/mining)."""
from pathlib import Path
import struct

from mining_resources_c import ROOT, resources

YIELDS, CATEGORIES, TEXT, END = 0xa3, 0x145, 0x14e, 0x53e


def record():
    from mining_parameters_c import resources as parameters
    data = parameters()
    if len(data) != 27 * 6 + 9:
        raise ValueError('mining parameter size changed')
    return data


def source():
    record()
    return ('/* Generated by tools/mining_tables_c.py from native mining resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const fe2_mining_yield *fe2_mining_yields;\n'
            'const uint8_t *fe2_mining_category_cargo;\n'
            'const uint8_t *fe2_mining_text_directory;\n'
            'int fe2_mining_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 171u) return -1;\n'
            '    fe2_mining_yields = (const fe2_mining_yield *)(const void *)image;\n'
            '    fe2_mining_category_cargo = image + 162u;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/mining/mining_tables.h')
    write_tables(parser.parse_args().output)
