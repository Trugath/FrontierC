"""Generate the frontier render port's tables from the native resources.
The arccosine lookup is the Q6 formula in math_samples."""
import csv
from pathlib import Path
from render_material_resources import read_materials

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'


def acos_table():
    from math_samples import acos_signed_q6
    return acos_signed_q6()


def record():
    import struct
    materials = read_materials(RESOURCES / 'texture_materials.tsv')
    material = b''.join(struct.pack('<H', word) for word in materials)
    with open(RESOURCES / 'coordinate_pair_rejection_masks.csv', newline='', encoding='ascii') as f:
        rejection = [int(v, 0) for row in csv.reader(f) for v in row if v.strip()]
    if len(rejection) != 15:
        raise ValueError('Expected 15 coordinate pair rejection masks')
    def bytes_table(name):
        with open(RESOURCES / name, newline='', encoding='ascii') as f:
            return [int(v, 0) for row in csv.reader(f) for v in row if v.strip()]
    tail = bytes_table('main_render_parameter_tail.csv')
    entries = bytes(tail[14:])
    base = 0x299d - 0x14 - 0x2902
    thresholds = bytes(tail[base:base + 42])
    coefficients = bytes_table('main_render_inline_curve.csv')
    if len(coefficients) != 33 or len(thresholds) != 42:
        raise ValueError('render tail layout changed')
    from resource_sources import csv_integers
    profiles = csv_integers(ROOT / 'data/video/scanline_shape_profiles.csv')
    outer = csv_integers(RESOURCES / 'paired_disc_outer_sizes.csv')
    inner = csv_integers(RESOURCES / 'paired_disc_inner_sizes.csv')
    if len(profiles) != 672 or len(outer) != 9 or len(inner) != 9:
        raise ValueError('Unexpected backend tables')
    return (struct.pack('<I', len(material)) + material + struct.pack('<15H', *rejection) +
            struct.pack('<I', len(entries)) + entries + bytes(coefficients) + thresholds +
            bytes(profiles) + bytes(outer) + bytes(inner))


def source():
    words = acos_table()
    rows = ',\n'.join('    ' + ', '.join(f'0x{v:04x}' for v in words[i:i + 8]) for i in range(0, len(words), 8))
    record()
    return ('/* Generated by tools/render_tables_c.py; do not edit. */\n'
            f'const uint16_t fe2_render_acos_table[{len(words)}] = {{\n{rows}\n}};\n'
            '#include <stddef.h>\n'
            'const uint8_t *fe2_render_material_data;\n'
            'uint32_t fe2_render_material_bytes;\n'
            'const uint16_t *fe2_render_pair_rejection;\n'
            'const uint8_t *fe2_render_context_entry_data;\n'
            'uint32_t fe2_render_context_entry_bytes;\n'
            'const uint8_t *fe2_render_curve_coefficients;\n'
            'const uint8_t *fe2_render_sample_thresholds;\n'
            'const uint8_t *fe2_render_shape_profiles;\n'
            'const uint8_t (*fe2_render_paired_disc_sizes)[9];\n'
            'int fe2_render_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    uint32_t materials, entries;\n'
            '    size_t at;\n'
            '    if (!image || count < 8u) return -1;\n'
            '    materials = (uint32_t)image[0] | ((uint32_t)image[1] << 8) | ((uint32_t)image[2] << 16) |\n'
            '        ((uint32_t)image[3] << 24);\n'
            '    at = 4u + materials;\n'
            '    if (at + 34u > count) return -1;\n'
            '    fe2_render_material_bytes = materials;\n'
            '    fe2_render_material_data = image + 4u;\n'
            '    fe2_render_pair_rejection = (const uint16_t *)(const void *)(image + at);\n'
            '    at += 30u;\n'
            '    entries = (uint32_t)image[at] | ((uint32_t)image[at + 1] << 8) |\n'
            '        ((uint32_t)image[at + 2] << 16) | ((uint32_t)image[at + 3] << 24);\n'
            '    at += 4u;\n'
            '    if (at + entries + 33u + 42u + 672u + 18u != count) return -1;\n'
            '    fe2_render_context_entry_bytes = entries;\n'
            '    fe2_render_context_entry_data = image + at;\n'
            '    at += entries;\n'
            '    fe2_render_curve_coefficients = image + at;\n'
            '    fe2_render_sample_thresholds = image + at + 33u;\n'
            '    fe2_render_shape_profiles = image + at + 75u;\n'
            '    fe2_render_paired_disc_sizes = (const uint8_t (*)[9])(const void *)(image + at + 75u + 672u);\n'
            '    return 0;\n'
            '}\n')


def backend_source():
    """Draw-backend tables: MCGA shape profiles and the paired-disc size maps."""
    def values(path):
        from resource_sources import csv_integers
        return csv_integers(path)
    profiles = values(ROOT / 'data/video/scanline_shape_profiles.csv')
    outer = values(RESOURCES / 'paired_disc_outer_sizes.csv')
    inner = values(RESOURCES / 'paired_disc_inner_sizes.csv')
    if len(profiles) != 672 or len(outer) != 9 or len(inner) != 9: raise ValueError('Unexpected backend tables')
    return ('const uint8_t fe2_render_shape_profiles[672] = {' + ', '.join(map(str, profiles)) + '};\n'
            'const uint8_t fe2_render_paired_disc_sizes[2][9] = {{' + ', '.join(map(str, outer)) + '}, {'
            + ', '.join(map(str, inner)) + '}};\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
