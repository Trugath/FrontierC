"""Generate the typed C tables of the drives port from the native drive
resources (data/drives): the 15 drive classes (range
factor, mass, name text) and the 16 misjump outcome selectors."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/drives'


def tables():
    from text_references import parse_selector
    rows = list(csv.reader((RESOURCES / 'parameters.csv').read_text().splitlines()))
    if rows and rows[0] == ['capacity', 'threshold', 'name_text']:
        rows = rows[1:]
    classes = [(int(row[0], 0), int(row[1], 0), parse_selector(row[2])) for row in rows]
    outcomes = [int(v, 0) for row in csv.reader((RESOURCES / 'outcomes.csv').read_text().splitlines())
                for v in row]
    if len(classes) != 15 or any(len(row) != 3 for row in classes) or len(outcomes) != 16:
        raise ValueError('drives drive tables changed')
    return classes, outcomes


def source():
    classes, outcomes = tables()
    lines = ['/* Generated by tools/hyperspace_tables_c.py from native drives resources; do not edit. */',
             'const fe2_drive_class fe2_hyperspace_drive_classes[FE2_DRIVE_CLASSES] = {']
    lines += [f'    {{{factor}, {mass}, {text:#x}}},' for factor, mass, text in classes]
    lines += ['};', 'const uint8_t fe2_hyperspace_outcomes[FE2_DRIVE_OUTCOMES] = {' +
              ', '.join(map(str, outcomes)) + '};']
    return '\n'.join(lines) + '\n'


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT / 'build/c/drives/hyperspace_tables.h')
    write_tables(parser.parse_args().output)
