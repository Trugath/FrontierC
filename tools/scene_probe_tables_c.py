"""Generate the frontier scene probe port's table from the native resources:
the contact axis permutations (contact_axis_permutations.csv; the first
three byte offsets of each row, as word indexes)."""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'


def axis_rows():
    with open(RESOURCES / 'contact_axis_permutations.csv', newline='', encoding='ascii') as f:
        return [[int(v) for v in row] for row in csv.reader(f) if row]


def table():
    rows = axis_rows()
    if len(rows) != 6 or any(len(row) < 3 or any(v < 0 or v % 2 or v // 2 > 255 for v in row[:3]) for row in rows):
        raise ValueError('probe axes')
    return bytes(v // 2 for row in rows for v in row[:3])


def source():
    return ('/* Generated by tools/scene_probe_tables_c.py; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t (*fe2_probe_axes)[3];\n'
            'int fe2_probe_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 18u) return -1;\n'
            '    fe2_probe_axes = (const uint8_t (*)[3])(const void *)image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
