"""Generate the image preamble (CS:0000h..008Eh) and the entry code bytes after it for the frontier objects
port from the native resources the original's preamble includes, in its
layout: adjustment words, equipment text selectors, the saved resource slot
(FFFFh), the equipment and class deployment maps, ten zero bytes, the effect
shift tail and strength words."""
import csv
import struct
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'data/main/frontier'


def values(name):
    with open(RESOURCES / f'{name}.csv', newline='', encoding='ascii') as f:
        return [int(v) for row in csv.reader(f) for v in row if v.strip()]


def preamble():
    def words(name): return b''.join(struct.pack('<H', v) for v in values(name))
    data = (words('main_object_adjustment_words') + words('main_equipment_text_selectors') + b'\xff\xff' +
            bytes(values('main_equipment_deployment_map')) + bytes(values('main_class_deployment_map')) +
            bytes(10) + words('main_effect_shift_tail') + words('main_effect_strength_words'))
    if len(data) != 0x8f: raise ValueError(f'preamble is {len(data):#x} bytes')
    # The strength words of kinds 14h..1Eh run on into the entry code's first
    # instructions (cli; mov ax, data segment; mov ss, ax; mov sp, 0FA04h;
    # sti; call): their bytes, with the relocated segment word unrelocated.
    return data + bytes.fromhex('fab854318ed0bc04fafbe855')


def source():
    if len(preamble()) != 0x9b:
        raise ValueError('objects preamble')
    return ('/* Generated by tools/objects_tables_c.py from the preamble resources; do not edit. */\n'
            '#include <stddef.h>\n'
            'const uint8_t *fe2_objects_preamble;\n'
            'int fe2_objects_bind(const uint8_t *image, size_t count)\n'
            '{\n'
            '    if (!image || count != 0x9bu) return -1;\n'
            '    fe2_objects_preamble = image;\n'
            '    return 0;\n'
            '}\n')


def write_tables(path):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(source(), encoding='ascii')
