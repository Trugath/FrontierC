/* Native session adapter; keep aligned with the named overlay state and services. */
/* The native state <-> the image of DS 0x1fc1..0x55ca a commander file holds. Each
 * annotated cell is stored little-endian at its address; object pointers are their
 * records' references (`ref`, `object`); other pointers are not in the image. */
typedef uint32_t (*fe2_image_ref)(void *context, const fe2_object *object);
typedef fe2_object *(*fe2_image_object)(void *context, uint32_t ref);
static inline void image_put(uint8_t *ds, unsigned at, unsigned size, uint64_t value)
{
    unsigned i;
    for (i = 0; i < size; ++i) ds[at + i] = (uint8_t)(value >> (8 * i));
}
static inline uint64_t image_get(const uint8_t *ds, unsigned at, unsigned size)
{
    uint64_t value = 0;
    unsigned i;
    for (i = 0; i < size; ++i) value |= (uint64_t)ds[at + i] << (8 * i);
    return value;
}
